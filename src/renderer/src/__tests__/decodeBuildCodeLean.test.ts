import { describe, it, expect } from 'vitest'
import zlib from 'node:zlib'
import { decodeBuildCodeLean, LeanBuildCodeError } from '../utils/decodeBuildCodeLean'

// Hand-rolled encoder for malformed-input tests only (real fixtures above come from the actual
// Python encoder) — matches the same base64url(zlib(json)) pipeline so it can construct payloads
// Python's own encoder would never produce (e.g. a non-numeric `v`), to prove the decoder rejects
// them rather than silently trusting an out-of-contract value.
function encodeForTest(obj: unknown): string {
  const compressed = zlib.deflateSync(Buffer.from(JSON.stringify(obj), 'utf-8'), { level: 9 })
  const b64url = compressed.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
  return `tli1_${b64url}`
}

// Generated by the REAL Python encoder (zlib.compress + base64.urlsafe_b64encode, matching

describe('decodeBuildCodeLean', () => {
  it('decodes a real Python-encoded tli1 code byte-for-byte into the original JSON', async () => {
    const decoded = await decodeBuildCodeLean(REAL_PYTHON_CODE)
    expect(decoded).toEqual(EXPECTED)
  })

  it('splits on the FIRST underscore only — a payload containing "_" is not mis-parsed', async () => {
    // Sanity check on the fixture itself: prove it actually contains a base64url '_' character,
    // so the "split on first underscore only" logic is genuinely exercised above, not vacuously
    // true because the fixture happened to have none.
    const payload = REAL_PYTHON_CODE.slice('tli1_'.length)
    expect(payload.includes('_')).toBe(true)
  })

  it('rejects a bad prefix', async () => {
    await expect(decodeBuildCodeLean('tli2_abc')).rejects.toThrow(LeanBuildCodeError)
  })

  it('rejects invalid base64', async () => {
    await expect(decodeBuildCodeLean('tli1_!!!not-base64!!!')).rejects.toThrow(LeanBuildCodeError)
  })

  it('rejects corrupt (non-inflatable) payload', async () => {
    await expect(decodeBuildCodeLean('tli1_AAAA')).rejects.toThrow(LeanBuildCodeError)
  })

  it('rejects an empty string', async () => {
    await expect(decodeBuildCodeLean('')).rejects.toThrow(LeanBuildCodeError)
  })

  it('rejects a non-numeric schema version instead of silently trusting it', async () => {
    const code = encodeForTest({ v: 'not-a-number', gear: [], skills: [] })
    await expect(decodeBuildCodeLean(code)).rejects.toThrow(LeanBuildCodeError)
  })

  it('rejects a schema version newer than this decoder has ever been checked against', async () => {
    const code = encodeForTest({ v: 999, gear: [], skills: [] })
    await expect(decodeBuildCodeLean(code)).rejects.toThrow(LeanBuildCodeError)
  })

  it('accepts a build with no `v` field at all (pre-versioning codes)', async () => {
    const decoded = await decodeBuildCodeLean(encodeForTest({ gear: [], skills: [] }))
    expect(decoded).toEqual({ gear: [], skills: [] })
  })
})

// ── Static reference-data source (web/CDN) ──────────────────────────────────────────────────────────────
// On the web build, the season-global catalogs are served as static gzipped JSON from a CDN (generated by
// backend/tools/export_web_data.py) instead of hitting the Python backend. Set VITE_STATIC_DATA_BASE to that
// base URL (e.g. https://data.tlibuilder.com). When unset (desktop), everything goes through IPC/HTTP as before.
// Layout: <BASE>/manifest.json -> {season}; <BASE>/<season>/<name>.json per catalog.
const STATIC_DATA_BASE: string = (import.meta.env?.VITE_STATIC_DATA_BASE as string | undefined) || ''
let staticSeason = ''
let webCompute = false   // web build: dispatch backend calls through the Pyodide worker instead of HTTP/IPC
type WebApi = typeof import('../web/pyodideCompute')
let webApi: WebApi | null = null   // loaded once in initApi (web only) so get/post can call it synchronously
// API path -> static filename (the reference catalogs served from the CDN on web: most load at startup;
// crosswalk-tables is fetched on demand by the Compendium importer).
const STATIC_CATALOGS: Record<string, string> = {
  '/skills': 'skills',
  '/legendary-gear': 'legendary_gear',
  '/legendary-gear-index': 'legendary_gear_index',
  '/craft-base-items': 'craft_base_items',
  '/craft-base-types': 'craft_base_types',
  '/grafts': 'grafts',
  '/hero-traits': 'hero_traits',
  '/hero-memories': 'hero_memories',
  '/conditions': 'conditions',
  '/pact-spirits': 'pact_spirits',
  '/verification-db': 'verification_db',
  '/glossary': 'glossary',
  '/help-db': 'help_db',
  '/crosswalk-tables': 'crosswalk_tables',   // Import from Compendium (web: served from the data CDN)
}
function staticCatalogUrl(path: string): string | null {
  if (!STATIC_DATA_BASE || !staticSeason) return null
  const name = STATIC_CATALOGS[path]
  return name ? `${STATIC_DATA_BASE}/${staticSeason}/${name}.json` : null
}

// Host root for bundled entity icons (served by the Python backend at /icons/<category>/<file>.webp).
// Images must load via a real URL even in IPC mode (an <img> can't go through the IPC bridge), so we
// resolve the port here and expose iconUrl() to turn a record's icon_url into a local server URL.
let ICON_BASE = ''
export function iconUrl(category: string, iconRef: string | null | undefined): string | null {
  if (!iconRef || !ICON_BASE) return null
  // Records store a full CDN icon_url; we pair on its basename, which matches the bundled file.
  const clean = iconRef.split('?')[0].split('#')[0]
  const file = clean.substring(clean.lastIndexOf('/') + 1)
  if (!file) return null
  return `${ICON_BASE}/${category}/${file}`
}

const verbose = typeof window !== 'undefined' && window.api?.isVerbose === true
const rlog = (...args: unknown[]) => { if (verbose) console.log('[api]', ...args) }
const rerr = (...args: unknown[]) => { if (verbose) console.error('[api]', ...args) }

async function probePort(port: number): Promise<boolean> {
  rlog(`probePort(${port}) — fetching /api/trees`)
  try {
    const res = await fetch(`http://127.0.0.1:${port}/api/trees`, {
      signal: AbortSignal.timeout(800),
    })
    rlog(`probePort(${port}) — status ${res.status}, ok=${res.ok}`)
    return res.ok
  } catch (e) {
    rlog(`probePort(${port}) — failed: ${e}`)
    return false
  }
}

export async function initApi(): Promise<void> {
  rlog('initApi — start, window.api defined:', typeof window !== 'undefined' && 'api' in window)
  // Resolve the static-data season from the CDN manifest (web build). Catalog reads then come from the CDN;
  // anything else still uses IPC/HTTP below.
  if (STATIC_DATA_BASE) {
    try {
      const m = await (await fetch(`${STATIC_DATA_BASE}/manifest.json`)).json()
      staticSeason = m.season || ''
      rlog(`initApi — static data base ${STATIC_DATA_BASE}, season ${staticSeason}`)
      // Web build (no Electron IPC): run compute in the Pyodide worker. Kick off its load in the background;
      // engineStats awaits readiness on first use.
      if (!window.api?.apiRequest && staticSeason) {
        webCompute = true
        webApi = await import('../web/pyodideCompute')
        webApi.initPyodideCompute(STATIC_DATA_BASE, staticSeason)
          .catch(e => rerr(`initApi — pyodide backend init failed: ${e}`))
      }
    } catch (e) {
      rerr(`initApi — failed to load static manifest from ${STATIC_DATA_BASE}: ${e}`)
    }
  }
  // Web build: catalogs come from the CDN and compute from the Pyodide worker — there's no local backend to
  // find, so skip the IPC/port-scan paths (which would otherwise spam CSP-blocked fetches to 127.0.0.1).
  if (webCompute) {
    ICON_BASE = `${STATIC_DATA_BASE}/icons`   // entity icons served from the CDN (export_web_data copies them)
    rlog('initApi — web mode: static catalogs + Pyodide compute; no backend')
    return
  }
  if (window.api?.apiRequest) {
    ipcMode = true
    rlog('initApi — Electron IPC path: waiting for port readiness via getPythonPort')
    const port = await window.api.getPythonPort()
    ICON_BASE = `http://127.0.0.1:${port}/icons`
    rlog(`initApi — IPC ready, ipcMode=true, ICON_BASE: ${ICON_BASE}`)
    return
  }
  rlog('initApi — browser path: scanning ports 8765-8774')
  for (let port = 8765; port <= 8774; port++) {
    if (await probePort(port)) {
      BASE = `http://127.0.0.1:${port}/api`
      ICON_BASE = `http://127.0.0.1:${port}/icons`
      rlog(`initApi — found server on port ${port}, BASE: ${BASE}`)
      return
    }
  }
  BASE = 'http://127.0.0.1:8765/api'
  ICON_BASE = 'http://127.0.0.1:8765/icons'
  rerr(`initApi — no server found on 8765-8774, defaulting BASE to: ${BASE}`)
}

async function get<T>(path: string, retries = 4): Promise<T> {
  // Web build: serve reference catalogs from the static CDN (gzipped JSON) instead of the backend.
  const staticUrl = staticCatalogUrl(path)
  if (staticUrl) {
    rlog(`GET (static) ${staticUrl}`)
    const res = await fetch(staticUrl)
    if (!res.ok) throw new Error(`GET ${staticUrl} → ${res.status}`)
    return res.json()
  }
  if (webCompute && webApi) return webApi.webApiRequest<T>('GET', `/api${path}`)
  if (ipcMode) {
    rlog(`GET (IPC) ${path}`)
    const result = await window.api!.apiRequest('GET', path) as { ok: boolean; status: number; data: T }
    if (!result.ok) throw new Error(`GET ${path} → ${result.status}`)
    return result.data
  }
  const url = `${BASE}${path}`
  for (let attempt = 0; attempt <= retries; attempt++) {
    rlog(`GET ${url} — attempt ${attempt + 1}/${retries + 1}`)
    try {
      const res = await fetch(url)
      rlog(`GET ${url} — status ${res.status}`)
      if (!res.ok) throw new Error(`GET ${path} → ${res.status}`)
      return await res.json()
    } catch (e) {
      const isNetwork = e instanceof TypeError
      rerr(`GET ${url} — error (isNetwork=${isNetwork}): ${e}`)
      if (!isNetwork || attempt === retries) throw e
      const delay = 400 * (attempt + 1)
      rlog(`GET ${url} — retrying in ${delay}ms`)
      await new Promise(r => setTimeout(r, delay))
    }
  }
  throw new Error(`GET ${path} failed`)
}

async function post<T>(path: string, body: unknown): Promise<T> {
  if (webCompute && webApi) return webApi.webApiRequest<T>('POST', `/api${path}`, body)
  if (ipcMode) {
    rlog(`POST (IPC) ${path}`)
    const result = await window.api!.apiRequest('POST', path, body) as { ok: boolean; status: number; data: T }
    if (!result.ok) throw new Error(`POST ${path} → ${result.status}`)
    return result.data
  }
  const url = `${BASE}${path}`
  rlog(`POST ${url}`)
  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
    signal: AbortSignal.timeout(15000),
  })
  rlog(`POST ${url} — status ${res.status}`)
  if (!res.ok) throw new Error(`POST ${path} → ${res.status}`)
  return res.json()
}

